<details class="explain">
  <summary>How zone temperatures are estimated</summary>
  <div>
    <p>Each zone is modelled as a mass that gains heat from the surroundings and loses it to the cooling unit:</p>
<pre class="code">leak    = leak_base × (1 − insulation) + door_open × door_leak × e^(−distance_to_door / door_reach) × (1 − 0.5 × insulation)
cooling = cooling_running × cool_strength × cooling_exposure × (0.4 + 0.6 × e^(−distance_to_cooler / cool_reach))

change per minute = [leak × (surrounding − T) + cooling × (setpoint − T)] / thermal_mass</pre>
    <p>The equation is solved exactly at every update, so long gaps between updates stay accurate.</p>
    <p>In hardware mode the physical reference sensor corrects the model. The difference between the real reading and the model’s prediction at the sensor is added to each zone, weighted by distance:</p>
<pre class="code">estimate = model + (sensor_actual − model_at_sensor) × e^(−distance_to_sensor / correction_length) + calibration_offset</pre>
    <p>A zone that contains the sensor shows the actual reading and is marked measured. In simulation mode the reference reading is generated by the same model with a little noise, and every zone is marked simulated. Before relying on estimates in a real store, record spot checks across the room and confirm the MAE is acceptable for the goods you keep.</p>
  </div>
</details>

